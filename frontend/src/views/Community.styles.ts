/** The status tint of a shared thing of yours (pending, hidden, removed, withdrawn). */
export const statusStyle = (status: string) =>
  status === 'pending'
    ? styles.stPending
    : status === 'hidden' || status === 'removed'
      ? styles.stOff
      : status === 'withdrawn'
        ? styles.stWithdrawn
        : null
